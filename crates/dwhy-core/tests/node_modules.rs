//! `node-modules` on temp-dir fixtures.

use std::fs;
use std::os::unix::fs::symlink;
use std::path::{Path, PathBuf};
use std::time::{SystemTime, UNIX_EPOCH};

use dwhy_core::detect::{self, DetectContext, Detector};
use dwhy_core::detectors::NodeModules;
use dwhy_core::mounts::MountTable;
use dwhy_core::report::{ActionKind, DockerSocket, Finding, Tier};
use dwhy_core::scan::{self, Progress, ScanOptions};
use dwhy_core::tree::{Markers, ScanTree};

const MB: usize = 1 << 20;

fn scan_tree(root: &Path) -> ScanTree {
    let roots = scan::prepare_roots(&[root.to_path_buf()], true).unwrap();
    let opts = ScanOptions {
        min_dir_bytes: 0,
        threads: 4,
        ..ScanOptions::default()
    };
    scan::scan(
        &roots,
        &opts,
        &MountTable::read().unwrap(),
        &Progress::default(),
    )
    .unwrap()
    .tree
}

fn ctx() -> DetectContext {
    DetectContext {
        uid: 1000,
        root: false,
        home: None,
        now: SystemTime::now()
            .duration_since(UNIX_EPOCH)
            .unwrap()
            .as_secs() as i64,
        tools: vec![],
        docker_socket: DockerSocket {
            path: "/nonexistent".into(),
            exists: false,
            accessible: false,
        },
        docker: dwhy_core::docker::Source::none(),
    }
}

fn write(p: &Path, bytes: usize) {
    fs::create_dir_all(p.parent().unwrap()).unwrap();
    fs::write(p, vec![7u8; bytes]).unwrap();
}

fn tmp() -> (tempfile::TempDir, PathBuf) {
    let t = tempfile::tempdir().unwrap();
    let root = fs::canonicalize(t.path()).unwrap();
    (t, root)
}

/// A project at `dir` with `package.json`, the given lockfiles and a
/// node_modules holding `mb` MiB. Returns the node_modules path.
fn project(dir: &Path, locks: &[&str], mb: usize) -> PathBuf {
    fs::create_dir_all(dir).unwrap();
    fs::write(dir.join("package.json"), r#"{"name":"app"}"#).unwrap();
    for l in locks {
        fs::write(dir.join(l), "lock").unwrap();
    }
    let nm = dir.join("node_modules");
    write(&nm.join("left-pad/index.js"), mb * MB);
    fs::write(nm.join("left-pad/package.json"), "{}").unwrap();
    nm
}

/// Raw detector output (before the nesting rule), sorted by path.
fn findings_in(tree: &ScanTree) -> Vec<Finding> {
    let mut f = NodeModules.detect(tree, &ctx()).unwrap();
    f.sort_by(|a, b| a.path.cmp(&b.path));
    f
}

fn findings(root: &Path) -> Vec<Finding> {
    findings_in(&scan_tree(root))
}

fn paths(f: &[Finding]) -> Vec<&str> {
    f.iter().map(|f| f.path.as_str()).collect()
}

fn s(p: &Path) -> &str {
    p.to_str().unwrap()
}

#[test]
fn finds_a_plain_npm_project() {
    let (_t, root) = tmp();
    let app = root.join("app");
    let nm = project(&app, &["package-lock.json"], 2);

    let tree = scan_tree(&root);
    let found = findings_in(&tree);
    assert_eq!(found.len(), 1);
    let f = &found[0];
    assert_eq!(f.path, s(&nm));
    assert_eq!(f.detector, "node-modules");
    assert_eq!(f.id, detect::finding_id("node-modules", &f.path));
    assert_eq!(f.tier, Tier::Rebuildable);
    let node = tree.node(tree.find(&nm).unwrap());
    assert_eq!(f.bytes, node.freeable());
    assert_eq!(f.bytes, node.total.allocated, "nothing is hardlinked");
    assert!(f.bytes >= 2 << 20);
    assert!(f.guards.is_empty());
    assert_eq!(f.action.kind, ActionKind::RemovePath);
    assert!(f.action.argv.is_none());
    assert_eq!(f.action.text, format!("remove {}", s(&nm)));
    assert_eq!(
        f.recovery.how.as_deref(),
        Some(format!("cd {} && npm ci", s(&app)).as_str())
    );
    assert!(
        f.recovery.cost.starts_with("npm ci "),
        "{}",
        f.recovery.cost
    );
    assert!(
        f.reason
            .starts_with(&format!("Node.js packages installed for {} (", s(&app))),
        "{}",
        f.reason
    );
    assert!(f.reason.contains("last written"), "{}", f.reason);
    assert!(!f.reason.contains("hardlinked"), "{}", f.reason);
    assert!(f.last_modified.is_some());
}

#[test]
fn recovery_follows_the_lockfile() {
    let (_t, root) = tmp();
    let cases: &[(&str, &[&str], Option<&str>)] = &[
        ("npm", &["package-lock.json"], Some("npm ci")),
        ("shrinkwrap", &["npm-shrinkwrap.json"], Some("npm ci")),
        ("pnpm", &["pnpm-lock.yaml"], Some("pnpm install")),
        ("yarn", &["yarn.lock"], Some("yarn install")),
        ("bun", &["bun.lock"], Some("bun install")),
        ("bunb", &["bun.lockb"], Some("bun install")),
        ("mixed", &["package-lock.json", "yarn.lock"], None),
        ("none", &[], None),
    ];
    for (name, locks, _) in cases {
        project(&root.join(name), locks, 2);
    }
    let found = findings(&root);
    for (name, _, cmd) in cases {
        let dir = root.join(name);
        let f = found
            .iter()
            .find(|f| f.path == s(&dir.join("node_modules")));
        if *name == "none" {
            assert!(f.is_none(), "no lockfile: not reported");
            continue;
        }
        let f = f.unwrap_or_else(|| panic!("{name}: no finding"));
        assert_eq!(f.tier, Tier::Rebuildable);
        match cmd {
            Some(cmd) => assert_eq!(
                f.recovery.how.as_deref(),
                Some(format!("cd {} && {cmd}", s(&dir)).as_str()),
                "{name}"
            ),
            None => {
                assert_eq!(f.recovery.how, None, "{name}");
                assert!(
                    f.recovery.cost.contains("lockfiles for npm and yarn"),
                    "{}",
                    f.recovery.cost
                );
            }
        }
    }
    assert_eq!(found.len(), cases.len() - 1);
}

#[test]
