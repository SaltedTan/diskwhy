/// pnpm hardlinks package files from its store into node_modules/.pnpm.
/// `store` names the fake store dir, which decides where the scan
/// attributes the shared inode (the lexicographically smallest path).
fn pnpm_fixture(root: &Path, store: &str) -> PathBuf {
    let nm = project(&root.join("app"), &["pnpm-lock.yaml"], 2);
    let store = root.join(store).join("v10/files/ab");
    write(&store.join("cafe"), 3 * MB);
    let pkg = nm.join(".pnpm/react@19.0.0/node_modules/react");
    fs::create_dir_all(&pkg).unwrap();
    fs::hard_link(store.join("cafe"), pkg.join("index.js")).unwrap();
    // A link inside node_modules only: removing it frees the file.
    write(&nm.join(".pnpm/a@1/node_modules/a/big.js"), MB);
    fs::create_dir_all(nm.join(".pnpm/b@1/node_modules/b")).unwrap();
    fs::hard_link(
        nm.join(".pnpm/a@1/node_modules/a/big.js"),
        nm.join(".pnpm/b@1/node_modules/b/big.js"),
    )
    .unwrap();
    nm
}

#[test]
fn bytes_hardlinked_from_a_pnpm_store_are_not_freeable() {
    for store in ["zz-pnpm-store", "a-pnpm-store"] {
        let (_t, root) = tmp();
        let nm = pnpm_fixture(&root, store);
        let tree = scan_tree(&root);
        let node = tree.node(tree.find(&nm).unwrap());
        let found = findings_in(&tree);
        assert_eq!(paths(&found), [s(&nm)], "{store}");
        let f = &found[0];
        assert_eq!(f.bytes, node.freeable(), "{store}");
        // The 2 MiB package and the internally linked 1 MiB file are freed;
        // the 3 MiB store file is not, wherever the scan attributed it.
        assert!(
            f.bytes >= 3 << 20 && f.bytes < 4 << 20,
            "{store}: bytes = {}",
            f.bytes
        );
        if store.starts_with("zz") {
            // Attributed to node_modules (sorts first), so counted as shared.
            assert!(node.shared >= 3 << 20 && node.shared < 4 << 20);
            assert!(
                f.reason.contains("more is hardlinked elsewhere"),
                "{}",
                f.reason
            );
        } else {
            // Attributed to the store: not in node_modules' total at all.
            assert_eq!(node.shared, 0);
            assert!(node.total.allocated < 4 << 20);
        }
    }
}

#[test]
fn a_store_outside_the_scan_still_counts_as_shared() {
    let (_t, root) = tmp();
    let nm = pnpm_fixture(&root, "store");
    let tree = scan_tree(&root.join("app"));
    let node = tree.node(tree.find(&nm).unwrap());
    assert!(node.shared >= 3 << 20 && node.shared < 4 << 20);
    let f = findings_in(&tree);
    assert_eq!(f.len(), 1);
    assert_eq!(f[0].bytes, node.freeable());
    assert!(f[0].bytes < 4 << 20, "{}", f[0].bytes);
}

#[test]
fn the_walk_records_lockfile_markers() {
    let (_t, root) = tmp();
    for (dir, file) in [
        ("npm", "package-lock.json"),
        ("shrink", "npm-shrinkwrap.json"),
        ("pnpm", "pnpm-lock.yaml"),
        ("yarn", "yarn.lock"),
        ("bun", "bun.lock"),
        ("bunb", "bun.lockb"),
        ("pw", "pnpm-workspace.yaml"),
    ] {
        write(&root.join(dir).join(file), 1);
    }
    fs::create_dir_all(root.join("dir-lock/yarn.lock")).unwrap();
    let tree = scan_tree(&root);
    let m = |p: &str| tree.node(tree.find(&root.join(p)).unwrap()).markers;
    assert!(m("npm").contains(Markers::NPM_LOCK));
    assert!(m("shrink").contains(Markers::NPM_LOCK));
    assert!(m("pnpm").contains(Markers::PNPM_LOCK));
    assert!(m("yarn").contains(Markers::YARN_LOCK));
    assert!(m("bun").contains(Markers::BUN_LOCK));
    assert!(m("bunb").contains(Markers::BUN_LOCK));
    assert!(m("pw").contains(Markers::PNPM_WORKSPACE));
    assert!(
        !m("dir-lock").contains(Markers::YARN_LOCK),
        "a directory is not a lockfile"
    );
}

#[test]
fn run_includes_node_modules() {
    let (_t, root) = tmp();
    let nm = project(&root.join("app"), &["package-lock.json"], 2);
    let tree = scan_tree(&root);
    let only = vec!["node-modules".to_string()];
    let (found, runs) = detect::run_with(
        &tree,
        &ctx(),
        &dwhy_core::detectors::registry(),
        Some(&only),
    );
    assert_eq!(paths(&found), [s(&nm)]);
    let run = runs.iter().find(|r| r.name == "node-modules").unwrap();
    assert!(run.ran);
    assert_eq!(run.findings, 1);
}
