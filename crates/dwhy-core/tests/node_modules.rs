#[test]
fn nested_node_modules_belong_to_the_outermost() {
    let (_t, root) = tmp();
    let nm = project(&root.join("app"), &["package-lock.json"], 2);
    // npm's nested install: a package with its own node_modules (and even a
    // lockfile, as some published packages ship one).
    let pkg = nm.join("foo");
    project(&pkg, &["package-lock.json"], 2);
    // pnpm's layout: node_modules/.pnpm/<pkg>/node_modules/<pkg>.
    let virt = nm.join(".pnpm/bar@1.0.0");
    write(&virt.join("node_modules/bar/index.js"), 2 * MB);
    fs::write(virt.join("package.json"), "{}").unwrap();
    fs::write(virt.join("pnpm-lock.yaml"), "lock").unwrap();

    assert_eq!(paths(&findings(&root)), [s(&nm)]);
}

#[test]
fn workspace_members_are_separate_findings() {
    let (_t, root) = tmp();
    // npm/yarn/bun style: workspaces in package.json, one lockfile at the root.
    let ws = root.join("ws");
    let ws_nm = project(&ws, &["package-lock.json"], 2);
    fs::write(
        ws.join("package.json"),
        r#"{"name":"ws","private":true,"workspaces":["packages/*"]}"#,
    )
    .unwrap();
    let a = project(&ws.join("packages/a"), &[], 2);
    let b = project(&ws.join("packages/b"), &[], 2);
    // pnpm style: pnpm-workspace.yaml, no workspaces field.
    let pw = root.join("pw");
    let pw_nm = project(&pw, &["pnpm-lock.yaml"], 2);
    fs::write(pw.join("pnpm-workspace.yaml"), "packages:\n  - apps/*\n").unwrap();
    let web = project(&pw.join("apps/web"), &[], 2);

    let found = findings(&root);
    let mut want = vec![s(&ws_nm), s(&a), s(&b), s(&pw_nm), s(&web)];
    want.sort();
    assert_eq!(paths(&found), want);
    let get = |p: &Path| found.iter().find(|f| f.path == s(p)).unwrap();
    assert_eq!(
        get(&a).recovery.how.as_deref(),
        Some(format!("cd {} && npm ci", s(&ws)).as_str())
    );
    assert!(
        get(&a).recovery.cost.contains("workspace root"),
        "{}",
        get(&a).recovery.cost
    );
    assert_eq!(
        get(&web).recovery.how.as_deref(),
        Some(format!("cd {} && pnpm install", s(&pw)).as_str())
    );
    assert!(!get(&ws_nm).recovery.cost.contains("workspace root"));
}

#[test]
fn a_lockfile_above_that_is_not_a_workspace_root_does_not_count() {
    let (_t, root) = tmp();
    // A parent project with a lockfile but no workspaces: its lockfile does
    // not describe the nested project, which has none of its own.
    let parent = root.join("parent");
    project(&parent, &["package-lock.json"], 2);
    let inner = project(&parent.join("tools/gen"), &[], 2);
    // A stray lockfile in a plain directory above a project.
    fs::write(root.join("yarn.lock"), "lock").unwrap();
    let lone = project(&root.join("lone"), &[], 2);

    let found = findings(&root);
    assert_eq!(paths(&found), [s(&parent.join("node_modules"))]);
    assert!(!paths(&found).contains(&s(&inner)));
    assert!(!paths(&found).contains(&s(&lone)));
}

