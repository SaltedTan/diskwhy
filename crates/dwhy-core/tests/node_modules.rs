#[test]
fn ignores_lookalikes() {
    let (_t, root) = tmp();
    // No package.json next to it (e.g. npm's global lib/node_modules).
    write(&root.join("lib/node_modules/x/index.js"), 2 * MB);
    fs::write(root.join("lib/package-lock.json"), "lock").unwrap();
    // package.json but no lockfile: shipped inside an app, not reinstallable.
    project(&root.join("vscode-server/server"), &[], 2);
    // Inside an orphan node_modules: a package next to its own package.json.
    let orphan = root.join("orphan/node_modules/pkg");
    project(&orphan, &["package-lock.json"], 2);
    // npx's installs, which user-cache reports.
    project(
        &root.join(".npm/_npx/15c61037b1978c83"),
        &["package-lock.json"],
        2,
    );
    // package.json is a symlink: not a marker.
    let sym = root.join("sym-pkg");
    project(&sym, &["package-lock.json"], 2);
    fs::remove_file(sym.join("package.json")).unwrap();
    symlink(root.join("app-real/package.json"), sym.join("package.json")).unwrap();
    // node_modules is a symlink: never followed or reported.
    let real = root.join("app-real");
    project(&real, &["package-lock.json"], 2);
    let link = root.join("app-link");
    fs::create_dir_all(&link).unwrap();
    fs::write(link.join("package.json"), "{}").unwrap();
    fs::write(link.join("package-lock.json"), "lock").unwrap();
    symlink(real.join("node_modules"), link.join("node_modules")).unwrap();
    // A regular file named node_modules.
    let file = root.join("file-nm");
    fs::create_dir_all(&file).unwrap();
    fs::write(file.join("package.json"), "{}").unwrap();
    fs::write(file.join("package-lock.json"), "lock").unwrap();
    fs::write(file.join("node_modules"), vec![0u8; 2 * MB]).unwrap();
    // Too small to report.
    project(&root.join("tiny"), &["package-lock.json"], 0);

    assert_eq!(
        paths(&findings(&root)),
        [s(&real.join("node_modules"))],
        "only the real project"
    );
}

