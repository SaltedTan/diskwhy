//! `node-modules`: installed Node.js dependencies.
//!
//! A directory named `node_modules` counts when the directory holding it has
//! a `package.json` and a lockfile can say how to reinstall it: one in the
//! project itself, or in the workspace root above it (a directory with
//! `pnpm-workspace.yaml`, or whose `package.json` has `workspaces`). Without
//! a lockfile there is no reliable reinstall: such trees usually shipped
//! inside an application (VS Code Server and its extensions), and removing
//! them breaks it, so they are not reported.
//!
//! Only the outermost `node_modules` is reported: the walk never looks inside
//! one, so packages' own nested `node_modules` belong to it. npx's installs
//! (`<npm cache>/_npx/<hash>/node_modules`) are left to `user-cache`, which
//! reports them as `review` because running npx tools load code from there.
//!
//! No tool-native command removes only `node_modules`, so the action is a
//! path removal limited to the directory; the recovery is the reinstall
//! command chosen by the lockfile, run in the directory that holds it.

use std::path::{Path, PathBuf};

use crate::detect::{DetectContext, Detector, age, finding_id, rfc3339, shell_quote};
use crate::report::{Action, ActionKind, Finding, Recovery, Tier};
use crate::tree::{Markers, NodeId, ScanTree};
use crate::units::human;

use super::read_head;

/// node_modules smaller than this are not worth a finding.
const MIN_BYTES: u64 = 1 << 20;

/// Largest `package.json` read when checking for `workspaces`.
const MAX_PACKAGE_JSON: usize = 1 << 20;

const NAME: &str = "node_modules";

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum Manager {
    Npm,
    Pnpm,
    Yarn,
    Bun,
}

/// Lockfile marker, its package manager, and the files behind the marker.
const LOCKS: &[(Markers, Manager, &[&str])] = &[
    (
        Markers::NPM_LOCK,
        Manager::Npm,
        &["package-lock.json", "npm-shrinkwrap.json"],
    ),
    (Markers::PNPM_LOCK, Manager::Pnpm, &["pnpm-lock.yaml"]),
    (Markers::YARN_LOCK, Manager::Yarn, &["yarn.lock"]),
    (Markers::BUN_LOCK, Manager::Bun, &["bun.lock", "bun.lockb"]),
];

const ANY_LOCK: Markers = Markers::NPM_LOCK
    .union(Markers::PNPM_LOCK)
    .union(Markers::YARN_LOCK)
    .union(Markers::BUN_LOCK);

impl Manager {
    fn name(self) -> &'static str {
        match self {
            Manager::Npm => "npm",
            Manager::Pnpm => "pnpm",
            Manager::Yarn => "yarn",
            Manager::Bun => "bun",
        }
    }

    fn reinstall(self) -> &'static str {
        match self {
            Manager::Npm => "npm ci",
            Manager::Pnpm => "pnpm install",
            Manager::Yarn => "yarn install",
            Manager::Bun => "bun install",
        }
    }

    fn cost(self) -> &'static str {
        match self {
            Manager::Npm => {
                "npm ci reinstalls every package from the lockfile, downloading what npm's cache no longer holds"
            }
            Manager::Pnpm => {
                "pnpm install relinks every package from its store, downloading any that were pruned"
            }
            Manager::Yarn => {
                "yarn install reinstalls every package from yarn.lock, downloading what yarn's cache no longer holds"
            }
            Manager::Bun => {
                "bun install reinstalls every package from the lockfile, downloading what bun's cache no longer holds"
            }
        }
    }
}

fn managers(m: Markers) -> Vec<Manager> {
    LOCKS
        .iter()
        .filter(|(mk, _, _)| m.contains(*mk))
        .map(|(_, mgr, _)| *mgr)
        .collect()
}

/// Where the project's lockfile is and which managers it names.
struct Lock {
    dir: PathBuf,
    managers: Vec<Manager>,
    /// The lockfile is in a workspace root above the project.
    workspace: bool,
}

pub struct NodeModules;

impl Detector for NodeModules {
    fn name(&self) -> &'static str {
        "node-modules"
    }

    fn detect(&self, tree: &ScanTree, ctx: &DetectContext) -> Result<Vec<Finding>, String> {
        let mut out = Vec::new();
        // Depth-first from each root, never descending into a node_modules:
        // everything below one belongs to it.
        let mut stack: Vec<NodeId> = tree
            .roots()
            .iter()
            .copied()
            .filter(|&r| {
                !Path::new(tree.name(r))
                    .components()
                    .any(|c| c.as_os_str() == NAME)
            })
            .collect();
        while let Some(id) = stack.pop() {
            for &child in tree.children(id) {
                if !tree.node(child).is_dir {
                    continue;
                }
                if tree.name(child) == NAME {
                    if let Some(f) = self.finding(tree, ctx, child, id) {
                        out.push(f);
                    }
                } else {
                    stack.push(child);
                }
            }
        }
        Ok(out)
    }
}

impl NodeModules {
    /// The finding for `node_modules` dir `id` in project dir `project`, if
    /// it qualifies.
    fn finding(
        &self,
        tree: &ScanTree,
        ctx: &DetectContext,
        id: NodeId,
        project: NodeId,
    ) -> Option<Finding> {
        let pm = tree.node(project).markers;
        if !pm.contains(Markers::PACKAGE_JSON) {
            return None;
        }
        let n = tree.node(id);
        let bytes = n.freeable();
        if bytes < MIN_BYTES {
            return None;
        }
        let project_dir = tree.path(project);
        // npx's own installs: <cache>/_npx/<hash>/node_modules. Checked on the
        // path, so it holds when `_npx` or `<hash>` is the scan root.
        if project_dir.parent().and_then(Path::file_name) == Some(std::ffi::OsStr::new("_npx")) {
            return None;
        }
        let lock = find_lock(tree, &project_dir, pm)?;
        let path_s = tree.path(id).to_string_lossy().into_owned();
        let dir_s = lock.dir.to_string_lossy().into_owned();

        let (how, cost) = match lock.managers.as_slice() {
            [m] => {
                let mut cost = m.cost().to_string();
                if lock.workspace {
                    cost.push_str(&format!(
                        "; run in the workspace root {}, which installs every member",
                        lock.dir.display()
                    ));
                }
                (
                    Some(format!("cd {} && {}", shell_quote(&dir_s), m.reinstall())),
                    cost,
                )
            }
            ms => (
                None,
                format!(
                    "{} has lockfiles for {}; reinstall with the one the project uses",
                    lock.dir.display(),
                    ms.iter()
                        .map(|m| m.name())
                        .collect::<Vec<_>>()
                        .join(" and ")
                ),
            ),
        };

        let mut reason = format!(
            "Node.js packages installed for {} ({}",
            project_dir.display(),
            human(bytes)
        );
        if n.shared > 0 {
            reason.push_str(&format!(
                "; {} more is hardlinked elsewhere, e.g. from a pnpm store or bun cache, and is not freed",
                human(n.shared)
            ));
        }
        reason.push_str(&format!(
            "); last written {} ago",
            age(ctx.now, n.newest_mtime)
        ));

        Some(Finding {
            id: finding_id(self.name(), &path_s),
            detector: self.name().into(),
            probe: None,
            evidence: None,
            bytes,
            nested_bytes: None,
            last_modified: Some(rfc3339(n.newest_mtime)),
            growth: None,
            tier: Tier::Rebuildable,
            reason,
            guards: Vec::new(),
            action: Action {
                kind: ActionKind::RemovePath,
                text: format!("remove {}", shell_quote(&path_s)),
                argv: None,
            },
            recovery: Recovery { cost, how },
            path: path_s,
        })
    }
}

/// The project's own lockfile, else the lockfile of the workspace root that
/// contains it. The search stops at the first ancestor that has a
/// `package.json`, a lockfile or `pnpm-workspace.yaml`: if that is not a
/// workspace root with a lockfile, the project has none.
fn find_lock(tree: &ScanTree, project: &Path, pm: Markers) -> Option<Lock> {
    if pm.intersects(ANY_LOCK) {
        return Some(Lock {
            dir: project.to_path_buf(),
            managers: managers(pm),
            workspace: false,
        });
    }
    let stop = ANY_LOCK
        .union(Markers::PACKAGE_JSON)
        .union(Markers::PNPM_WORKSPACE);
    for dir in project.ancestors().skip(1) {
        let m = markers_at(tree, dir);
        if !m.intersects(stop) {
            continue;
        }
        if m.intersects(ANY_LOCK) && is_workspace_root(dir, m) {
            return Some(Lock {
                dir: dir.to_path_buf(),
                managers: managers(m),
                workspace: true,
            });
        }
        return None;
    }
    None
}

/// Markers of `dir`: from the tree when it was scanned, else read from disk
/// without following symlinks (an ancestor above the scan root).
fn markers_at(tree: &ScanTree, dir: &Path) -> Markers {
    if let Some(id) = tree.find(dir) {
        return tree.node(id).markers;
    }
    let mut m = Markers::empty();
    let names = LOCKS
        .iter()
        .flat_map(|(_, _, files)| files.iter())
        .chain(&["package.json", "pnpm-workspace.yaml"]);
    for name in names {
        let is_file = std::fs::symlink_metadata(dir.join(name)).is_ok_and(|md| md.is_file());
        m.insert(Markers::for_entry(name.as_bytes(), is_file, false));
    }
    m
}

fn is_workspace_root(dir: &Path, m: Markers) -> bool {
    if m.contains(Markers::PNPM_WORKSPACE) {
        return true;
    }
    if !m.contains(Markers::PACKAGE_JSON) {
        return false;
    }
    read_head(&dir.join("package.json"), MAX_PACKAGE_JSON)
        .and_then(|b| serde_json::from_slice::<serde_json::Value>(&b).ok())
        .is_some_and(|v| v.get("workspaces").is_some_and(|w| !w.is_null()))
}
